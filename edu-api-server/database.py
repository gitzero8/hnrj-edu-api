DB_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'edu_system.db')


def get_conn():
    """获取数据库连接"""
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    """初始化数据库表结构"""
    conn = get_conn()
    c = conn.cursor()

    # 用户表
    c.execute('''CREATE TABLE IF NOT EXISTS users (
        user_no TEXT PRIMARY KEY,
        password TEXT NOT NULL,
        name TEXT,
        birthday TEXT,
        gender TEXT,
        idno TEXT,
        phone TEXT,
        user_type TEXT DEFAULT '2',
        academy_name TEXT,
        cls_name TEXT,
        major_name TEXT,
        entrance_year TEXT,
        training_level TEXT,
        school TEXT DEFAULT '湖南软件职业技术大学',
        in_grade TEXT,
        sfzczxkt TEXT DEFAULT '1'
    )''')

    # 学期表
    c.execute('''CREATE TABLE IF NOT EXISTS semesters (
        semester_id TEXT PRIMARY KEY,
        semester_name TEXT,
        is_current TEXT DEFAULT '0'
    )''')

    # 时间模式表
    c.execute('''CREATE TABLE IF NOT EXISTS time_modes (
        kbjcmsid TEXT PRIMARY KEY,
        kbjcmsmc TEXT,
        mrms TEXT DEFAULT '1'
    )''')

    # 课程表
    c.execute('''CREATE TABLE IF NOT EXISTS courses (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        user_no TEXT,
        semester_id TEXT,
        course_name TEXT,
        teacher_name TEXT,
        class_week TEXT,
        class_week_details TEXT,
        week_day TEXT,
        start_time TEXT,
        end_time TEXT,
        class_time TEXT,
        week_note_detail TEXT,
        classroom_name TEXT,
        classroom_nub TEXT,
        building_name TEXT,
        location TEXT,
        ktmc TEXT,
        khfs TEXT,
        xkrs INTEGER DEFAULT 0,
        jx0404id TEXT,
        jx0408id TEXT,
        is_repeat_code TEXT DEFAULT '0',
        button_code TEXT DEFAULT '0',
        fzmc TEXT DEFAULT '',
        courses_note INTEGER DEFAULT 0
    )''')

    # 成绩表
    c.execute('''CREATE TABLE IF NOT EXISTS grades (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        user_no TEXT,
        curriculum_attributes TEXT,
        course_name TEXT,
        cur_semester_name TEXT,
        course_nature TEXT,
        examination_nature TEXT,
        kcbh TEXT,
        credit REAL,
        cj0708id TEXT,
        fraction TEXT
    )''')

    # 管理员表
    c.execute('''CREATE TABLE IF NOT EXISTS admins (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        username TEXT UNIQUE NOT NULL,
        password TEXT NOT NULL,
        name TEXT,
        role TEXT DEFAULT 'admin',
        created_at TEXT DEFAULT (datetime('now', 'localtime'))
    )''')

    # 教学周次表
    c.execute('''CREATE TABLE IF NOT EXISTS teaching_weeks (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        semester_id TEXT NOT NULL,
        week_number INTEGER NOT NULL,
        start_date TEXT,
        end_date TEXT,
        is_holiday TEXT DEFAULT '0',
        note TEXT DEFAULT ''
    )''')

    conn.commit()
    conn.close()


